-- Smart Study / StudyFlow database schema
-- Target: Oracle Database 12c+
-- Derived from JPA entities in studyflow-backend.
-- Run as a schema user with permission to create tables.
-- Schema only; this does not copy existing MySQL records.

CREATE TABLE users (
  id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR2(100 CHAR) NOT NULL,
  email VARCHAR2(150 CHAR) NOT NULL,
  password VARCHAR2(255 CHAR) NOT NULL,
  gender VARCHAR2(10 CHAR),
  date_of_birth DATE,
  phone_number VARCHAR2(30 CHAR),
  profile_image VARCHAR2(500 CHAR),
  email_verified NUMBER(1) DEFAULT 0 NOT NULL,
  verification_code VARCHAR2(6 CHAR),
  verification_code_expiry TIMESTAMP(6),
  created_at TIMESTAMP(6) NOT NULL,
  updated_at TIMESTAMP(6) NOT NULL,
  CONSTRAINT uk_users_email UNIQUE (email),
  CONSTRAINT chk_users_email_verified CHECK (email_verified IN (0,1))
);

CREATE TABLE subjects (
  id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR2(100 CHAR) NOT NULL,
  description VARCHAR2(500 CHAR),
  color VARCHAR2(50 CHAR),
  user_id NUMBER(19) NOT NULL,
  CONSTRAINT fk_subjects_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE INDEX idx_subjects_user_id ON subjects(user_id);

CREATE TABLE study_sessions (
  id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  start_time TIMESTAMP(6) NOT NULL,
  end_time TIMESTAMP(6),
  duration_minutes NUMBER(10) DEFAULT 0 NOT NULL,
  notes CLOB,
  user_id NUMBER(19) NOT NULL,
  subject_id NUMBER(19) NOT NULL,
  CONSTRAINT fk_study_sessions_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT fk_study_sessions_subject FOREIGN KEY (subject_id) REFERENCES subjects(id) ON DELETE CASCADE
);
CREATE INDEX idx_study_sessions_user_id ON study_sessions(user_id);
CREATE INDEX idx_study_sessions_subject_id ON study_sessions(subject_id);
CREATE INDEX idx_study_sessions_start_time ON study_sessions(start_time);

CREATE TABLE study_goals (
  id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR2(200 CHAR) NOT NULL,
  target_minutes NUMBER(10) NOT NULL,
  current_minutes NUMBER(10) DEFAULT 0 NOT NULL,
  start_date DATE NOT NULL,
  end_date DATE NOT NULL,
  completed NUMBER(1) DEFAULT 0 NOT NULL,
  user_id NUMBER(19) NOT NULL,
  subject_id NUMBER(19),
  CONSTRAINT chk_study_goals_completed CHECK (completed IN (0,1)),
  CONSTRAINT fk_study_goals_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT fk_study_goals_subject FOREIGN KEY (subject_id) REFERENCES subjects(id) ON DELETE SET NULL
);
CREATE INDEX idx_study_goals_user_id ON study_goals(user_id);
CREATE INDEX idx_study_goals_subject_id ON study_goals(subject_id);

CREATE TABLE friendships (
  id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  requester_id NUMBER(19) NOT NULL,
  addressee_id NUMBER(19) NOT NULL,
  status VARCHAR2(20 CHAR) DEFAULT 'PENDING' NOT NULL,
  created_at TIMESTAMP(6) NOT NULL,
  updated_at TIMESTAMP(6) NOT NULL,
  CONSTRAINT uk_friendship_pair UNIQUE (requester_id, addressee_id),
  CONSTRAINT chk_friendships_status CHECK (status IN ('PENDING','ACCEPTED','DECLINED')),
  CONSTRAINT fk_friendships_requester FOREIGN KEY (requester_id) REFERENCES users(id),
  CONSTRAINT fk_friendships_addressee FOREIGN KEY (addressee_id) REFERENCES users(id)
);
CREATE INDEX idx_friendships_addressee_id ON friendships(addressee_id);

CREATE TABLE study_call_logs (
  id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id NUMBER(19) NOT NULL,
  room_code VARCHAR2(80 CHAR) NOT NULL,
  joined_at TIMESTAMP(6) NOT NULL,
  left_at TIMESTAMP(6),
  duration_seconds NUMBER(19),
  call_type VARCHAR2(20 CHAR) DEFAULT 'GROUP' NOT NULL,
  CONSTRAINT fk_study_call_logs_user FOREIGN KEY (user_id) REFERENCES users(id)
);
CREATE INDEX idx_study_call_logs_user_id ON study_call_logs(user_id);
CREATE INDEX idx_study_call_logs_room_code ON study_call_logs(room_code);

CREATE TABLE email_verifications (
  id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR2(150 CHAR) NOT NULL,
  code VARCHAR2(6 CHAR) NOT NULL,
  expires_at TIMESTAMP(6) NOT NULL,
  used NUMBER(1) DEFAULT 0 NOT NULL,
  CONSTRAINT chk_email_verifications_used CHECK (used IN (0,1))
);
CREATE INDEX idx_email_verifications_email ON email_verifications(email);
CREATE INDEX idx_email_verifications_expires_at ON email_verifications(expires_at);
